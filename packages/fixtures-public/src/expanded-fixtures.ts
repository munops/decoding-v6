import type { PublicFixture } from './index'
export function publicCases(
  detector: string,
  positive: (string | Uint8Array)[],
  edge: (string | Uint8Array)[],
  negative: (string | Uint8Array)[],
): PublicFixture[] {
  return (
    [
      ['positive', positive],
      ['edge', edge],
      ['negative', negative],
    ] as const
  ).flatMap(([kind, values]) =>
    values.map((input, index) => ({
      id: `${detector}-${kind}-${index + 1}`,
      detector,
      input,
      class: kind,
    })),
  )
}
